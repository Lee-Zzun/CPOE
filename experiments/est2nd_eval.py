"""2차 기준 실측표(복원): feasibility(in-C_K) + 계산비용(적합시간), K=4와 K=10.

6 데이터 × 3 추정법 × {K=4, K=10}에 대해 raw 추정의 in-C_K(Y/N)와 적합 시간(중앙값, s)을
고차 평가와 동일 적합경로(highk_optimal_k._fit_one)로 측정 → results/tables/est2nd.tex.
데이터별로 K=4·K=10 두 행(multirow)으로 묶어 고차에서의 변화를 보인다.
[2026-07 복원] 논문 본문에서는 est2nd 표가 제거되었으므로(리뷰 대응용 검증 도구로만 유지),
출력 경로를 삭제된 report/tables/에서 results/tables/로 옮겼다.
"""
from __future__ import annotations

import statistics
import sys
import time
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
for p in (str(ROOT), str(ROOT / "src"), str(ROOT / "experiments")):
    if p not in sys.path:
        sys.path.insert(0, p)
try:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
except Exception:  # noqa: BLE001
    pass

import highk_optimal_k as ok_  # noqa: E402  (_fit_one, ESTIMATORS)
from highk_report import _load, ALL_DATASETS, EST_SHORT  # noqa: E402

KS = [4, 10]
REP = 3
SEED = 20260606
N = 1500
SHORTS = ["MoM", "Seq", "Joint"]


def _yn(b):
    return "" if b is None else ("Y" if b else "N")


def _ft(t):
    return f"{t:.3g}"


def main():
    data = {}  # (name, K) -> {short: (inck, time)}
    for name in ALL_DATASETS:
        s = _load(name, N, SEED).astype(int)
        for K in KS:
            for est in ok_.ESTIMATORS:
                inck = None
                ts = []
                for _ in range(REP):
                    t0 = time.perf_counter()
                    try:
                        _, _, _, ck = ok_._fit_one(s, est, K)
                        inck = bool(ck)
                    except Exception:  # noqa: BLE001
                        inck = None
                    ts.append(time.perf_counter() - t0)
                data[(name, K)] = data.get((name, K), {})
                data[(name, K)][EST_SHORT[est]] = (inck, statistics.median(ts))
            r = data[(name, K)]
            print(f"[{name} K={K}] in-C_K = {_yn(r['MoM'][0])}/{_yn(r['Seq'][0])}/{_yn(r['Joint'][0])}  "
                  f"time = {_ft(r['MoM'][1])}/{_ft(r['Seq'][1])}/{_ft(r['Joint'][1])}s", flush=True)

    lines = [
        "% Auto-generated by experiments/est2nd_eval.py",
        "\\begin{table}[H]", "\\centering",
        "\\caption{적합 동등 하의 2차 기준 실측($K{=}4,10$): raw 추정의 feasibility(in-$C_K$, Y/N)와 "
        "적합 시간(동일 환경 중앙값, 초). MoM은 raw 경험투영이라 비실행(N) 시 사후 $C_K$ 투영이 필요하고 "
        "차수가 오르면 더 빈번해지며, Sequential$\\cdot$Joint는 경성 KKT로 항상 실행가능.}",
        "\\label{tab:est2nd}", "\\small",
        "\\begin{tabular}{llrrrrrr}", "\\toprule",
        "데이터 & $K$ & \\multicolumn{3}{c}{in-$C_K$} & \\multicolumn{3}{c}{적합 시간 (s)} \\\\",
        "\\cmidrule(lr){3-5}\\cmidrule(lr){6-8}",
        " & & MoM & Seq & Joint & MoM & Seq & Joint \\\\", "\\midrule",
    ]
    for i, name in enumerate(ALL_DATASETS):
        for j, K in enumerate(KS):
            r = data[(name, K)]
            cks = [_yn(r[sh][0]) for sh in SHORTS]
            ts = [_ft(r[sh][1]) for sh in SHORTS]
            lead = f"\\multirow{{{len(KS)}}}{{*}}{{{name}}}" if j == 0 else ""
            lines.append(" & ".join([lead, str(K)] + cks + ts) + " \\\\")
        if i < len(ALL_DATASETS) - 1:
            lines.append("\\midrule")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    out_dir = ROOT / "results" / "tables"
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "est2nd.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote results/tables/est2nd.tex")


if __name__ == "__main__":
    main()
