"""교차모델 비교표 (K=4) — Poisson / NB / CMP / CPOE(K=4)의 in-sample L¹.

§5.1 tab:k4-crossmodel의 단일 출처 생성기. highk_report.py의 D 섹션과 *동일* 경로
(base_.poisson/nb_fitted_pmf, ok_._fit_one("MoM",·)/_pmf, _l1(emp,·))를 재사용하므로
highk_pmfbase_*.pdf 그림의 수치와 정확히 일치한다. 모든 열은 경험 pmf 대비 in-sample L¹.

  Poisson:  MoM(=MLE), μ=X̄.
  NB(β,c):  MoM. 과대산포 아님(σ²≤μ; 예: S1)이면 Poisson으로 폴백.
  CMP:      적률매칭 (λ,ν) = CPOE의 K=0.
  CPOE(K=4): MoM 적합, 왜도·첨도 틸트(θ₃,θ₄).

실데이터(FIFA/Insurance-smoker)와 시뮬(S1–S4) 모두 같은 정의(경험 pmf 대비 L¹)로 비교한다
(시뮬도 참 pmf가 아닌 경험 pmf 기준 — 실데이터 행과 동일 척도).

출력:
  papers/supp/tables/perf_crossmodel.tex  — 통합 표 (모델 4행 × 데이터 6열)
  results/crossmodel.csv             — 동일 수치 CSV

사용: python experiments/crossmodel_eval.py [--datasets FIFA,S1]
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Dict, List

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
for _p in (str(ROOT), str(ROOT / "src"), str(ROOT / "experiments")):
    if _p not in sys.path:
        sys.path.insert(0, _p)

try:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
except Exception:  # noqa: BLE001
    pass

from cpoe import baselines as base_  # noqa: E402
from cpoe.diagnostics import empirical_pmf  # noqa: E402
from _datasets import load_dataset  # noqa: E402
from highk_optimal_k import _l1, _fit_one, _pmf  # noqa: E402
from highk_scenarios import HIGHK_SCENARIOS  # noqa: E402

ALL_DATASETS = ["FIFA", "Insurance-smoker", "S1", "S2", "S3", "S4"]
MODELS = ["Poisson", "NB", "CMP", "CPOE (K=4)"]
# 표 열 머리글(공간 절약): 긴 데이터명은 약칭.
COL_HEAD = {"Insurance-smoker": "Ins-smoker"}


def _load(name: str, N: int, seed: int) -> np.ndarray:
    """highk_report._load와 동일: 시뮬은 시드 고정 샘플러, 실데이터는 로더."""
    if name in HIGHK_SCENARIOS:
        i = list(HIGHK_SCENARIOS).index(name)
        return HIGHK_SCENARIOS[name].sampler(
            N, np.random.default_rng(seed + 1000 * (i + 1))).astype(int)
    return load_dataset(name).astype(int)


def _l2(emp: np.ndarray, p: np.ndarray) -> float:
    """비가중 L2 = sqrt(Σ_x (p_emp − p̂)^2). l2_eval._l2와 동일 정의(재정규화 없음)로
    tab:k4-estimators/tab:highk-all의 L2 수치와 일관."""
    emp = np.asarray(emp, float); p = np.asarray(p, float)
    return float(np.sqrt(np.sum((emp - p) ** 2)))


def crossmodel_fits(sample: np.ndarray) -> Dict[str, Dict[str, float]]:
    """한 데이터셋의 네 모델 in-sample L¹·비가중 L² (highk_report D 섹션과 동일 계산).

    반환 {"L1": {model: v}, "L2": {model: v}}.
    """
    s = np.asarray(sample, dtype=int)
    max_x = int(s.max())
    grid = np.arange(max_x + 1)
    emp = empirical_pmf(s, max_x + 1)

    p_pois, _ = base_.poisson_fitted_pmf(s, grid)
    p_nb, _ = base_.nb_fitted_pmf(s, grid)
    # CMP = CPOE의 K=0 (적률매칭 λ,ν), CPOE(K=4)는 MoM 틸트.
    lam0, nu0, th0, _ = _fit_one(s, "MoM", 0)
    p_cmp = _pmf(lam0, nu0, th0, max_x)
    lam4, nu4, th4, _ = _fit_one(s, "MoM", 4)
    p_cpoe = _pmf(lam4, nu4, th4, max_x)

    pmfs = {"Poisson": p_pois, "NB": p_nb, "CMP": p_cmp, "CPOE (K=4)": p_cpoe}
    return {
        "L1": {m: _l1(emp, p) for m, p in pmfs.items()},
        "L2": {m: _l2(emp, p) for m, p in pmfs.items()},
    }


def write_csv(table: Dict[str, Dict[str, Dict[str, float]]], names: List[str], out: Path) -> None:
    out.parent.mkdir(parents=True, exist_ok=True)
    with out.open("w", encoding="utf-8") as f:
        f.write("metric,model," + ",".join(names) + "\n")
        for metric in ("L1", "L2"):
            for m in MODELS:
                f.write(metric + "," + m + "," +
                        ",".join(f"{table[nm][metric][m]:.5f}" for nm in names) + "\n")


def write_tex(table: Dict[str, Dict[str, Dict[str, float]]], names: List[str], out: Path) -> None:
    out.parent.mkdir(parents=True, exist_ok=True)
    heads = " & ".join(COL_HEAD.get(nm, nm) for nm in names)
    ncol = len(names)
    disp = {"Poisson": "Poisson", "NB": "NB", "CMP": "CMP", "CPOE (K=4)": r"CPOE ($K{=}4$)"}
    lines = [
        "% Auto-generated by experiments/crossmodel_eval.py",
        r"\begin{table}[H]", r"\centering",
        r"\caption{Cross-model goodness of fit: in-sample $L^1$ and unweighted $L^2$ (all by MoM at $K{=}4$, against the empirical pmf). "
        r"CMP $=$ CPOE($K{=}0$). NB falls back to Poisson when the data are not over-dispersed (S1).}",
        r"\label{tab:k4-crossmodel}",
        r"\small",
        r"\begin{tabular}{l" + "r" * ncol + "}",
        r"\toprule",
        f"Model & {heads} \\\\",
        r"\midrule",
    ]
    panels = [("L1", r"$L^1$"), ("L2", r"unweighted $L^2$")]
    for pi, (metric, plabel) in enumerate(panels):
        lines.append(f"\\multicolumn{{{ncol + 1}}}{{l}}{{\\emph{{{plabel}}}}} \\\\")
        for m in MODELS:
            row = " & ".join(f"{table[nm][metric][m]:.5f}" for nm in names)
            lines.append(f"{disp[m]} & {row} \\\\")
        if pi < len(panels) - 1:
            lines.append(r"\midrule")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="교차모델(Poisson/NB/CMP/CPOE) K=4 L¹ 비교표")
    ap.add_argument("--datasets", default=",".join(ALL_DATASETS))
    ap.add_argument("--N", type=int, default=1500)
    ap.add_argument("--seed", type=int, default=20260606)
    ap.add_argument("--out-dir", type=Path, default=ROOT / "results")
    ap.add_argument("--tex-dir", type=Path, default=ROOT / "papers" / "supp" / "tables")
    args = ap.parse_args(argv)

    names = [x.strip() for x in args.datasets.split(",") if x.strip()]
    table: Dict[str, Dict[str, Dict[str, float]]] = {}
    for nm in names:
        s = _load(nm, args.N, args.seed)
        table[nm] = crossmodel_fits(s)
        cells = "  ".join(f"{m}=L1:{table[nm]['L1'][m]:.5f}/L2:{table[nm]['L2'][m]:.5f}"
                          for m in MODELS)
        print(f"[{nm}] N={s.size}  {cells}", flush=True)

    write_csv(table, names, args.out_dir / "crossmodel.csv")
    write_tex(table, names, args.tex_dir / "perf_crossmodel.tex")
    print(f"[crossmodel] 완료 → {args.out_dir/'crossmodel.csv'}, "
          f"{args.tex_dir/'perf_crossmodel.tex'}", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
