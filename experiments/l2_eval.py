"""비가중 L2 평가 — 최종 보고서 §L2 평가용 표/그림 생성기.

§5(고차 K)와 **동일한 적합 경로**(highk_optimal_k._fit_one/_pmf, highk_optimal_k._l1)를
재사용하여, 6개 데이터 × 격자 K={0,4,6,8,10} × 세 추정법(MoM/Seq/Joint)에 대해
in-sample L1과 **비가중 L2**를 함께 산출한다. 따라서 L1 열은 기존 highk_estl1_* 수치를
재현하며(파이프라인 검증), L2 열만 신규다.

  L1 = Σ_x |p_emp(x) − p̂(x)|   (highk_optimal_k._l1)
  L2 = sqrt( Σ_x (p_emp(x) − p̂(x))^2 )   (비가중; MoM의 가중 χ²과 무관)

출력:
  papers/supp/tables/l2_{slug}.tex   — K행 × {MoM,Seq,Joint}×{L1,L2} 표
  results/l2_{slug}.csv         — 동일 수치 CSV
  papers/supp/figs/l2_{slug}.pdf/png — 좌=L1 vs K, 우=L2 vs K (세 추정법)

사용: python experiments/l2_eval.py [--datasets FIFA,S1]
"""
from __future__ import annotations

import argparse
import sys
import time
from pathlib import Path
from typing import Dict

import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
for _p in (str(ROOT), str(ROOT / "src"), str(ROOT / "experiments")):
    if _p not in sys.path:
        sys.path.insert(0, _p)

try:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
except Exception:  # noqa: BLE001
    pass

from cpoe.diagnostics import empirical_pmf  # noqa: E402
from highk_optimal_k import _l1  # noqa: E402
import highk_optimal_k as ok_  # noqa: E402  (_fit_one, _pmf, ESTIMATORS)
from highk_report import _load, _slug, GRID, ALL_DATASETS, EST_SHORT  # noqa: E402


def _l2(emp: np.ndarray, p: np.ndarray) -> float:
    emp = np.asarray(emp, float); p = np.asarray(p, float)
    return float(np.sqrt(np.sum((emp - p) ** 2)))


def _fmt(v) -> str:
    if v is None or not np.isfinite(v):
        return ""
    return f"{float(v):.4f}"


def _compute(name: str, N: int, seed: int) -> Dict[str, Dict[int, tuple]]:
    """{short_est: {K: (L1, L2)}}. 적합은 §5와 동일 경로."""
    s = _load(name, N, seed)
    max_x = int(s.max())
    emp = empirical_pmf(s, max_x + 1)
    out: Dict[str, Dict[int, tuple]] = {}
    for est in ok_.ESTIMATORS:
        short = EST_SHORT[est]
        row: Dict[int, tuple] = {}
        for K in GRID:
            try:
                lam, nu, th, _ = ok_._fit_one(s, est, K)
                p = ok_._pmf(lam, nu, th, max_x)
                row[K] = (_l1(emp, p), _l2(emp, p))
            except Exception as e:  # noqa: BLE001
                print(f"    [warn] {name}/{est}/K={K} 실패: {e}", flush=True)
                row[K] = (np.nan, np.nan)
        out[short] = row
    return out


def _write_tex(name: str, slug: str, res: Dict[str, Dict[int, tuple]],
               tex_dir: Path) -> None:
    shorts = ["MoM", "Seq", "Joint"]
    lines = [
        "% Auto-generated by experiments/l2_eval.py",
        "\\begin{table}[H]", "\\centering",
        f"\\caption{{{name}: in-sample $L^1$ and unweighted $L^2$ by truncation order $K$ "
        f"for the three estimators (MoM/Seq/Joint).}}",
        f"\\label{{tab:l2-{slug}}}", "\\small",
        "\\begin{tabular}{rrrrrrr}", "\\toprule",
        "$K$ & \\multicolumn{3}{c}{$L^1$} & \\multicolumn{3}{c}{unweighted $L^2$} \\\\",
        "\\cmidrule(lr){2-4}\\cmidrule(lr){5-7}",
        " & MoM & Seq & Joint & MoM & Seq & Joint \\\\", "\\midrule",
    ]
    for K in GRID:
        l1s = [_fmt(res[sh][K][0]) for sh in shorts]
        l2s = [_fmt(res[sh][K][1]) for sh in shorts]
        lines.append(" & ".join([str(K)] + l1s + l2s) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    (tex_dir / f"l2_{slug}.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")


def _write_csv(slug: str, res: Dict[str, Dict[int, tuple]], out_dir: Path) -> None:
    import csv
    shorts = ["MoM", "Seq", "Joint"]
    with (out_dir / f"l2_{slug}.csv").open("w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(["K"] + [f"{sh}_{m}" for sh in shorts for m in ("L1", "L2")])
        for K in GRID:
            row = [K]
            for sh in shorts:
                l1, l2 = res[sh][K]
                row += [_fmt(l1), _fmt(l2)]
            w.writerow(row)


def _plot(name: str, slug: str, res: Dict[str, Dict[int, tuple]], fig_dir: Path) -> None:
    styles = {"MoM": ("-o", "#444444"), "Seq": ("-s", "#1f4e9c"), "Joint": ("-^", "#c0392b")}
    fig, (axL, axR) = plt.subplots(1, 2, figsize=(11, 4.0))
    for sh in ("MoM", "Seq", "Joint"):
        st, col = styles[sh]
        ks = GRID
        l1 = [res[sh][k][0] for k in GRID]
        l2 = [res[sh][k][1] for k in GRID]
        axL.plot(ks, l1, st, ms=4, lw=1.4, color=col, label=sh)
        axR.plot(ks, l2, st, ms=4, lw=1.4, color=col, label=sh)
    for ax, ttl, yl in ((axL, f"{name}: $L^1$ vs $K$", "$L^1$ discrepancy"),
                        (axR, f"{name}: unweighted $L^2$ vs $K$", "$L^2$ discrepancy")):
        ax.set_xlabel("truncation order $K$"); ax.set_ylabel(yl)
        ax.set_title(ttl, fontsize=10); ax.grid(True, alpha=0.25)
        ax.legend(fontsize=8, loc="best"); ax.set_xticks(GRID)
    fig.tight_layout()
    fig_dir.mkdir(parents=True, exist_ok=True)
    fig.savefig(fig_dir / f"l2_{slug}.pdf", bbox_inches="tight")
    fig.savefig(fig_dir / f"l2_{slug}.png", dpi=150, bbox_inches="tight")
    plt.close(fig)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--datasets", default=",".join(ALL_DATASETS))
    ap.add_argument("--N", type=int, default=1500)
    ap.add_argument("--seed", type=int, default=20260606)
    ap.add_argument("--fig-dir", type=Path, default=ROOT / "papers" / "supp" / "figs")
    ap.add_argument("--tex-dir", type=Path, default=ROOT / "papers" / "supp" / "tables")
    ap.add_argument("--out-dir", type=Path, default=ROOT / "results")
    args = ap.parse_args(argv)
    for d in (args.fig_dir, args.tex_dir, args.out_dir):
        d.mkdir(parents=True, exist_ok=True)

    names = [x.strip() for x in args.datasets.split(",") if x.strip()]
    for nm in names:
        t0 = time.perf_counter()
        res = _compute(nm, args.N, args.seed)
        slug = _slug(nm)
        _write_tex(nm, slug, res, args.tex_dir)
        _write_csv(slug, res, args.out_dir)
        _plot(nm, slug, res, args.fig_dir)
        # 콘솔 검증 출력 (L1은 기존 highk_estl1과 일치해야 함)
        mom = res["MoM"]
        l1s = ", ".join(f"K{K}={_fmt(mom[K][0])}" for K in GRID)
        print(f"[{nm}] done ({time.perf_counter()-t0:.1f}s)  MoM L1: {l1s}", flush=True)
    print("\n[l2_eval] 완료.", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
