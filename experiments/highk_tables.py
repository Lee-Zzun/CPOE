"""고차 K 후속 보고서 — LaTeX(.tex) + CSV 표 라이터.

θ̂ 등 조합-분음부호 회피를 위해 헤더는 수식($\\theta_3$)으로 작성(기존 관행).
출력: papers/supp/tables/highk_*.tex + results/highk_*.csv
"""
from __future__ import annotations

import csv
from pathlib import Path
from typing import List, Sequence

import numpy as np


def _fmt(v, nd: int = 4) -> str:
    if v is None:
        return ""
    try:
        f = float(v)
    except (TypeError, ValueError):
        return str(v)
    if not np.isfinite(f):
        return ""
    return f"{f:.{nd}f}"


def _write(out_tex: Path, lines: List[str]) -> None:
    out_tex = Path(out_tex)
    out_tex.parent.mkdir(parents=True, exist_ok=True)
    out_tex.write_text("\n".join(lines) + "\n", encoding="utf-8")


def _write_csv(out_csv: Path, header: Sequence[str], rows: Sequence[Sequence]) -> None:
    out_csv = Path(out_csv)
    out_csv.parent.mkdir(parents=True, exist_ok=True)
    with out_csv.open("w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(header)
        w.writerows(rows)


# ----------------------------------------------------------------------------
# L1-by-K 표 — K를 열로, L1 한 행 (Supp 데이터별 차수별 표)
# ----------------------------------------------------------------------------
def write_l1byk_multi(grid: List[int], series: "dict[str, list]", out_tex: Path, out_csv: Path,
                      caption: str, label: str) -> None:
    """K를 열로, 계열을 행으로. series: {표시라벨: [L1...] (grid 정렬)}."""
    colspec = "l" + "r" * len(grid)
    header = ["Order $K$"] + [str(k) for k in grid]
    tex = ["% Auto-generated by experiments/highk_tables.py",
           "\\begin{table}[H]", "\\centering", f"\\caption{{{caption}}}",
           f"\\label{{{label}}}", f"\\begin{{tabular}}{{{colspec}}}", "\\toprule",
           " & ".join(header) + " \\\\", "\\midrule"]
    csv_rows = []
    for lab, vals in series.items():
        cells = [_fmt(v) for v in vals]
        tex.append(" & ".join([lab] + cells) + " \\\\")
        csv_rows.append([lab] + cells)
    tex += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    _write(out_tex, tex)
    _write_csv(out_csv, ["series"] + [str(k) for k in grid], csv_rows)
